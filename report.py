def cluster_components(components):
    """Group components into subsystems by path prefix."""
    clusters = {}
    for c in components:
        path = c["path"]
        if path.startswith("live-coding/calypso"):
            cluster = "calypso"
        elif path.startswith("live-coding/"):
            cluster = "live-coding"
        elif path.startswith("expert-sleepers/"):
            cluster = "expert-sleepers"
        elif path.startswith("SamplesProject/"):
            cluster = "samples"
        elif path.startswith("rig-control/"):
            cluster = "rig-control"
        else:
            cluster = "other"
        clusters.setdefault(cluster, []).append(c)
    return clusters


